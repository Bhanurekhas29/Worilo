export function PartnerIcon({ name, size = 20 }) {
  const Cmp = partnerIcons[name]?.Cmp
  return Cmp ? <Cmp size={size} strokeWidth={1.8} aria-hidden="true" /> : null
}

export function HighlightIcon({ name, size = 18 }) {
  const Cmp = highlightIcons[name]?.Cmp
  return Cmp ? <Cmp size={size} strokeWidth={1.8} aria-hidden="true" /> : null
}

export default function Icon({ name, size = 20 }) {
  const Cmp = icons[name]
  return Cmp ? <Cmp size={size} strokeWidth={1.8} aria-hidden="true" /> : null
}
